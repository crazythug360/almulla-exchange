function closeMenuEl(menuId, btnId) {
  const menu = document.getElementById(menuId);
  const btn = document.getElementById(btnId);
  if (!menu || menu.hidden) return false;
  menu.hidden = true;
  btn?.setAttribute("aria-expanded", "false");
  return true;
}

function closeThemeMenu() {
  return closeMenuEl("themeMenu", "themeBtn");
}

function closeFontMenu() {
  return closeMenuEl("fontMenu", "fontBtn");
}

function closeSizeMenu() {
  return closeMenuEl("sizeMenu", "sizeBtn");
}

function closeAlertSettings() {
  const panel = document.getElementById("alertSettings");
  if (!panel || panel.hidden) return false;
  panel.classList.remove("is-open");
  panel.setAttribute("aria-hidden", "true");
  document.getElementById("alertSettingsBtn")?.setAttribute("aria-expanded", "false");
  window.setTimeout(() => {
    if (!panel.classList.contains("is-open")) panel.hidden = true;
  }, 320);
  return true;
}

function openAlertSettings() {
  const panel = document.getElementById("alertSettings");
  const btn = document.getElementById("alertSettingsBtn");
  if (!panel) return;
  closeAppearanceMenus();
  panel.hidden = false;
  panel.setAttribute("aria-hidden", "false");
  btn?.setAttribute("aria-expanded", "true");
  requestAnimationFrame(() => panel.classList.add("is-open"));
  syncToastLayoutUi();
  syncToastFilterUi();
}

function previewToastSettings() {
  const filter = getToastFilter();
  const layout = getToastLayout();
  const kind = filter === "all" ? "success" : filter;
  toast({
    title: toastCopy().toastPreview || "Preview notification",
    desc: `${toastLayoutLabel(layout)} · ${document.querySelector(`[data-set-toast-filter="${filter}"] span[data-i18n]`)?.textContent || filter}`,
  }, kind);
}

function closeAppearanceMenus() {
  const themeClosed = closeThemeMenu();
  const fontClosed = closeFontMenu();
  const sizeClosed = closeSizeMenu();
  const alertClosed = closeAlertSettings();
  return themeClosed || fontClosed || sizeClosed || alertClosed;
}

function bindPicker(pickerId, btnId, menuId, attr, apply) {
  const picker = document.getElementById(pickerId);
  const btn = document.getElementById(btnId);
  const menu = document.getElementById(menuId);
  if (!picker || !btn || !menu) return;

  btn.addEventListener("click", (e) => {
    e.stopPropagation();
    const open = menu.hidden;
    closeAppearanceMenus();
    menu.hidden = !open;
    btn.setAttribute("aria-expanded", open ? "true" : "false");
  });
  menu.addEventListener("click", (e) => e.stopPropagation());
  picker.querySelectorAll(`[${attr}]`).forEach((opt) => {
    opt.addEventListener("click", () => {
      apply(opt.getAttribute(attr));
      closeAppearanceMenus();
    });
  });
}

