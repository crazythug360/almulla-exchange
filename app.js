function initAppearance() {
  let storedTheme = "current";
  let storedFont = "outfit";
  let storedSize = "large";
  try {
    storedTheme = localStorage.getItem(THEME_KEY);
    storedFont = localStorage.getItem(FONT_KEY);
    storedSize = localStorage.getItem(SIZE_KEY);
  } catch {
    storedTheme = "current";
    storedFont = "outfit";
    storedSize = "large";
  }
  applyTheme(storedTheme);
  applyFont(storedFont);
  applySize(storedSize);
  bindPicker("themePicker", "themeBtn", "themeMenu", "data-set-theme", applyTheme);
  bindPicker("fontPicker", "fontBtn", "fontMenu", "data-set-font", applyFont);
  bindPicker("sizePicker", "sizeBtn", "sizeMenu", "data-set-size", applySize);
  initAlertSettings();
  document.addEventListener("click", closeAppearanceMenus);
}

