function syncReset() {
  if (!newPass || !resetBtn) return;
  const value = newPass.value;
  const rules = {
    length: value.length >= 8 && value.length <= 15,
    lower: /[a-z]/.test(value),
    upper: /[A-Z]/.test(value),
    number: /\d/.test(value),
    special: /[!@$%]/.test(value),
    match: value.length > 0 && value === confirmPass.value,
  };
  Object.entries(rules).forEach(([key, ok]) => {
    const el = document.querySelector(`.pass-hint [data-rule="${key}"]`);
    if (!el) return;
    if (ok) {
      if (el.classList.contains("is-met")) return;
      el.classList.add("is-met");
      if (prefersReducedMotion()) {
        el.classList.add("is-gone");
        el.setAttribute("aria-hidden", "true");
      }
    } else {
      el.classList.remove("is-met", "is-gone");
      el.removeAttribute("aria-hidden");
    }
  });
  const hint = document.querySelector(".pass-hint");
  if (hint) {
    const items = hint.querySelectorAll("[data-rule]");
    const complete =
      items.length > 0 && [...items].every((el) => el.classList.contains("is-met"));
    hint.classList.toggle("is-complete", complete);
    if (complete) hint.setAttribute("aria-hidden", "true");
    else hint.removeAttribute("aria-hidden");
  }
  resetBtn.disabled = !Object.values(rules).every(Boolean);
}

