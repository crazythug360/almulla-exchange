function amePageBackFallback(explicit) {
  if (explicit && !String(explicit).startsWith("#")) {
    const file = ameFileName(explicit);
    if (file && AME_PAGES.has(file)) return explicit;
  }
  if (ameIsLoginGate()) return "index.html";
  return typeof ameHasSession === "function" && ameHasSession() ? "dashboard.html" : "index.html";
}

function amePageBack(explicitFallback) {
  const fallback = amePageBackFallback(explicitFallback);
  try {
    const ref = document.referrer;
    if (ref) {
      const u = new URL(ref);
      if (u.origin === location.origin) {
        const destFile = ameFileName(u.pathname);
        const here = ameFileName(location.href);
        if (destFile && destFile !== here) {
          if (window.history.length > 1) {
            window.history.back();
            return;
          }
          ameNavigate(destFile + (u.search || "") + (u.hash || ""));
          return;
        }
      }
    }
  } catch {
    /* ignore */
  }
  if (window.history.length > 1) {
    window.history.back();
    return;
  }
  ameNavigate(fallback);
}

