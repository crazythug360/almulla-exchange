function toastCopy() {
  const lang = document.documentElement.lang === "ar" ? "ar" : "en";
  return (window.copy && window.copy[lang]) || {};
}

function toastIcon(kind) {
  if (kind === "success") {
    return `<svg class="toast__icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" aria-hidden="true"><circle cx="12" cy="12" r="9"/><path d="m8 12.2 2.4 2.4L16.2 9"/></svg>`;
  }
  if (kind === "error") {
    return `<svg class="toast__icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" aria-hidden="true"><circle cx="12" cy="12" r="9"/><path d="M15 9 9 15M9 9l6 6"/></svg>`;
  }
  return `<svg class="toast__icon" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" aria-hidden="true"><circle cx="12" cy="12" r="9"/><path d="M12 8.2v5.2M12 16.6h.1"/></svg>`;
}

function toastDesc(message) {
  if (message && typeof message === "object") {
    if (message.desc) return message.desc;
    if (Array.isArray(message.lines)) return message.lines.filter(Boolean).join(" ");
    return "";
  }
  return String(message || "");
}

function toastTitle(message, kind) {
  const copy = toastCopy();
  if (message && typeof message === "object" && message.title) return message.title;
  if (kind === "success") return copy.toastSuccessTitle || "Success";
  if (kind === "error") return copy.toastErrorTitle || "Error";
  return copy.toastInfoTitle || "Information";
}

function toastCardHtml(kind, title, desc, closeLabel) {
  const text = desc || title || copyFallbackDesc(kind);
  const label = closeLabel || "Close notification";
  return `<button class="toast__close" type="button" aria-label="${label}"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" aria-hidden="true"><path d="M8 8l8 8M16 8l-8 8"/></svg></button><div class="toast__head">${toastIcon(kind)}</div><div class="toast__body"><p class="toast__desc">${text}</p></div>`;
}

function dismissToast(el, outMs = 700) {
  if (!el || el.dataset.dismissed) return;
  el.dataset.dismissed = "1";
  if (el._toastTimer) clearTimeout(el._toastTimer);
  if (el._toastOutTimer) clearTimeout(el._toastOutTimer);
  el.classList.remove("is-on");
  const stack = el.closest(".toast-stack");
  el._toastOutTimer = setTimeout(() => {
    el.remove();
    syncToastBackdrop(stack);
  }, outMs);
  syncToastBackdrop(stack);
}

function copyFallbackDesc(kind) {
  const copy = toastCopy();
  if (kind === "error") return copy.toastErrorRetry || "Please review and try again.";
  return "";
}

const TOAST_LAYOUT_KEY = "ame-toast-layout";
const TOAST_FILTER_KEY = "ame-toast-filter";

function normalizeToastLayout(value) {
  if (value === "top" || value === "top-right" || value === "top-right-dark" || value === "top-right-glass") {
    return value;
  }
  return "corner";
}

function toastLayoutLabel(layout) {
  const copy = toastCopy();
  if (layout === "top") return copy.toastStyleTop || "Top center";
  if (layout === "top-right") return copy.toastStyleTopRight || "Top right (white)";
  if (layout === "top-right-dark") return copy.toastStyleTopRightDark || "Top right (dark)";
  if (layout === "top-right-glass") return copy.toastStyleTopRightGlass || "Top right (glass)";
  return copy.toastStyleCorner || "Bottom corner";
}

function normalizeToastFilter(value) {
  if (value === "error" || value === "success" || value === "info") return value;
  return "all";
}

function getToastLayout() {
  return normalizeToastLayout(document.documentElement.dataset.toastLayout);
}

function getToastFilter() {
  return normalizeToastFilter(document.documentElement.dataset.toastFilter);
}

function syncToastLayoutUi(layout) {
  const current = normalizeToastLayout(layout ?? document.documentElement.dataset.toastLayout);
  document.querySelectorAll("[data-set-toast-layout]").forEach((btn) => {
    const on = btn.dataset.setToastLayout === current;
    btn.classList.toggle("is-on", on);
    btn.setAttribute("aria-pressed", on ? "true" : "false");
  });
}

function syncToastFilterUi(filter) {
  const current = normalizeToastFilter(filter ?? document.documentElement.dataset.toastFilter);
  document.querySelectorAll("[data-set-toast-filter]").forEach((btn) => {
    const on = btn.dataset.setToastFilter === current;
    btn.classList.toggle("is-on", on);
    btn.setAttribute("aria-pressed", on ? "true" : "false");
  });
}

function applyToastLayout(next) {
  const layout = normalizeToastLayout(next);
  document.documentElement.dataset.toastLayout = layout;
  try {
    localStorage.setItem(TOAST_LAYOUT_KEY, layout);
  } catch {
    /* private mode */
  }
  syncToastLayoutUi(layout);
  ensureToastBackdrop(getToastStack());
}

function applyToastFilter(next) {
  const filter = normalizeToastFilter(next);
  document.documentElement.dataset.toastFilter = filter;
  try {
    localStorage.setItem(TOAST_FILTER_KEY, filter);
  } catch {
    /* private mode */
  }
  syncToastFilterUi(filter);
}

function syncToastBackdrop(stack) {
  if (!stack?.classList.contains("toast-stack--top")) return;
  const hasToasts = stack.querySelectorAll(".toast").length > 0;
  stack.classList.toggle("is-active", hasToasts);
}

function ensureToastBackdrop(stack) {
  if (!stack) return;
  stack.querySelector(".toast-stack__backdrop")?.remove();
  stack.classList.remove("is-active");
}

function getToastStack() {
  const layout = getToastLayout();
  let stack = document.querySelector(".toast-stack");
  if (!stack) {
    stack = document.createElement("div");
    stack.setAttribute("aria-live", "polite");
    document.body.appendChild(stack);
  }
  stack.className = `toast-stack toast-stack--${layout}`;
  ensureToastBackdrop(stack);
  return stack;
}

function initToastPreferences() {
  let layout = "corner";
  let filter = "all";
  try {
    layout = localStorage.getItem(TOAST_LAYOUT_KEY) || layout;
    filter = localStorage.getItem(TOAST_FILTER_KEY) || filter;
  } catch {
    /* private mode */
  }
  applyToastLayout(layout);
  applyToastFilter(filter);
}

function toast(message, type) {
  const stack = getToastStack();
  const kind = type === "success" || type === "error" ? type : "info";
  const el = document.createElement("div");
  el.className = `toast toast--${kind}`;
  const title = toastTitle(message, kind);
  const desc = toastDesc(message);
  const outMs = 700;
  el.innerHTML = toastCardHtml(kind, title, desc, toastCopy().toastClose);
  el.querySelector(".toast__close")?.addEventListener("click", () => dismissToast(el, outMs));
  stack.appendChild(el);
  requestAnimationFrame(() => el.classList.add("is-on"));
  syncToastBackdrop(stack);
  const hideMs = kind === "error" ? 8500 : 7000;
  el._toastTimer = setTimeout(() => dismissToast(el, outMs), hideMs);
}

