function ameFileName(href) {
  if (!href) return "";
  try {
    const url = new URL(href, window.location.href);
    return decodeURIComponent(url.pathname.split("/").pop() || "");
  } catch {
    return String(href).split("?")[0].split("#")[0].split("/").pop() || "";
  }
}

function ameSamePage(href) {
  const target = ameFileName(href);
  const current = ameFileName(window.location.href);
  return Boolean(target) && target === current;
}

function ameNavigate(href) {
  if (!href || ameNavigating || ameSamePage(href)) return;
  if (ameIsLoginGate() && !ameAuthExit && !ameIsPublicPage(href)) return;
  ameNavigating = true;
  try {
    sessionStorage.setItem(AME_ENTER_KEY, "1");
  } catch {
    /* private mode */
  }
  if (ameReduceMotion) {
    window.location.href = href;
    return;
  }
  document.documentElement.classList.add("is-leaving");
  window.setTimeout(() => {
    window.location.href = href;
  }, 350);
}

