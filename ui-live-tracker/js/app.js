function ameReadSession() {
  try {
    return JSON.parse(sessionStorage.getItem(AME_SESSION_KEY) || "null");
  } catch {
    return null;
  }
}

function ameWriteSession(data) {
  try {
    sessionStorage.setItem(AME_SESSION_KEY, JSON.stringify(data));
  } catch {
    /* private mode */
  }
}

function ameClearSession() {
  try {
    sessionStorage.removeItem(AME_SESSION_KEY);
  } catch {
    /* private mode */
  }
}

